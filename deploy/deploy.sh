#!/usr/bin/env bash
# ------------------------------------------------------------------
# Деплой на VPS. Запускать на сервере:
#
#   cd /var/www/auto-svet.by/app && ./deploy/deploy.sh
#
# Что изменилось после появления админки. Раньше сборка складывалась в
# releases/, и деплой сводился к переключению символической ссылки — это
# работало, пока сайт был папкой с файлами. Теперь сайт — процесс, у
# которого своё состояние: база в var/, загруженные фото в public/img,
# кеш пересобранных страниц в .next. Гонять их между папками релизов
# бессмысленно и опасно, поэтому приложение живёт прямо в репозитории, а
# деплой пересобирает его на месте и перезапускает сервис.
#
# Цена: перезапуск занимает пару секунд, и в это время сайт не отвечает.
# Если понадобится обновляться без единого потерянного запроса, ставится
# второй юнит на соседнем порту и nginx переключается между ними.
# ------------------------------------------------------------------
set -euo pipefail

APP="/var/www/auto-svet.by/app"
SERVICE="autosvet"

cd "$APP"

echo "==> Забираю изменения"
git pull --ff-only

echo "==> Ставлю зависимости"
# npm ci ставит строго то, что в package-lock.json — сборка воспроизводима.
npm ci --no-audit --no-fund

echo "==> Собираю сайт"
# prebuild сам прогонит импорт данных и препроцессор картинок; заново
# жмутся только новые фотографии.
#
# Сборка идёт до перезапуска намеренно: если она упадёт (опечатка в
# шаблоне, ошибка типов), скрипт прервётся на этом месте и старый процесс
# продолжит работать со старой сборкой. Сайт не заметит неудачного деплоя.
npm run build

echo "==> Перезапускаю $SERVICE"
sudo systemctl restart "$SERVICE"

echo "==> Жду, пока поднимется"
for attempt in $(seq 1 30); do
  if curl -fsS --max-time 2 -o /dev/null localhost:3000/; then
    echo "    сайт отвечает (попытка $attempt)"
    break
  fi
  if [ "$attempt" -eq 30 ]; then
    echo "    ВНИМАНИЕ: сайт не поднялся за 30 секунд!"
    echo "    Смотрите: journalctl -u $SERVICE -n 50"
    exit 1
  fi
  sleep 1
done

echo "==> Проверяю ключевые адреса"
for url in / /catalog/ /sitemap.xml; do
  code=$(curl -s -o /dev/null -w '%{http_code}' "localhost:3000$url")
  echo "    $code  $url"
  [ "$code" = "200" ] || { echo "    ВНИМАНИЕ: $url отвечает $code"; exit 1; }
done

# Админка обязана отвечать редиректом на форму входа. Если она вдруг
# отдаст 200 без куки — значит проверка доступа отвалилась, и это гораздо
# хуже упавшей сборки.
admin=$(curl -s -o /dev/null -w '%{http_code}' localhost:3000/admin/)
if [ "$admin" = "307" ] || [ "$admin" = "302" ]; then
  echo "    $admin  /admin/ (уводит на вход — верно)"
else
  echo "    ВНИМАНИЕ: /admin/ отвечает $admin вместо редиректа на вход!"
  exit 1
fi

echo "==> Готово. Сайт обновлён."
