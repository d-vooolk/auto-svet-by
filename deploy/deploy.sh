#!/usr/bin/env bash
# ------------------------------------------------------------------
# Деплой на VPS. Запускать на сервере:
#
#   cd /var/www/auto-svet.by/app && ./deploy/deploy.sh
#
# Что делает: забирает изменения, пересобирает сайт в отдельную папку и
# только после успешной сборки переключает на неё символическую ссылку.
# Пока идёт сборка, посетители видят предыдущую версию; если сборка упала
# (например, опечатка в JSON), на сайте вообще ничего не меняется.
# ------------------------------------------------------------------
set -euo pipefail

ROOT="/var/www/auto-svet.by"
APP="$ROOT/app"           # репозиторий
RELEASES="$ROOT/releases" # собранные версии
CURRENT="$ROOT/current"   # ссылка на текущую, её раздаёт nginx
KEEP=5                    # сколько прошлых версий держать для отката

cd "$APP"

echo "==> Забираю изменения"
git pull --ff-only

echo "==> Ставлю зависимости"
# npm ci ставит строго то, что в package-lock.json — сборка воспроизводима.
npm ci --no-audit --no-fund

echo "==> Собираю сайт"
# prebuild сам прогонит препроцессор картинок; заново жмутся только новые.
npm run build

RELEASE="$RELEASES/$(date +%Y%m%d-%H%M%S)"
echo "==> Раскладываю в $RELEASE"
mkdir -p "$RELEASES"
cp -r out "$RELEASE"

echo "==> Переключаю current"
# Через временную ссылку и mv: переключение атомарное, посетитель не может
# попасть на полусобранную версию.
ln -sfn "$RELEASE" "$CURRENT.tmp"
mv -Tf "$CURRENT.tmp" "$CURRENT"

echo "==> Чищу старые версии (оставляю $KEEP)"
ls -1dt "$RELEASES"/*/ 2>/dev/null | tail -n "+$((KEEP + 1))" | xargs -r rm -rf

# Сервис заказов сам замечает новый variants.json по времени изменения
# файла, перезапуск ему не нужен. Но проверить, что он жив, стоит.
echo "==> Проверяю сервис заказов"
if curl -fsS --max-time 5 localhost:8787/health > /dev/null; then
  echo "    сервис заказов отвечает"
else
  echo "    ВНИМАНИЕ: сервис заказов не отвечает — заказы не дойдут!"
  echo "    Посмотрите: systemctl status autosvet-order"
fi

echo "==> Готово. Сайт обновлён."
